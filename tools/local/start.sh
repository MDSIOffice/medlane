#!/usr/bin/env bash
# Local copy of Medlane for testing load and performance on this machine.
#   bash tools/local/start.sh            start everything (first run also seeds sample data)
#   bash tools/local/start.sh --reseed   wipe local records and seed again
# Then open http://127.0.0.1:8787  (superadmin@medlane.local / LocalTest!2026)
#
# Pieces: local Supabase in Docker (Postgres + Auth + REST, the same products production uses),
# the repo's schema + migrations from docs/, and the real Worker (src/worker.js + public/) under
# `wrangler dev` with local Durable Objects and R2. Nothing here talks to production.
set -euo pipefail
cd "$(dirname "$0")/../.."

if ! docker info >/dev/null 2>&1; then
  echo "Starting Docker Desktop…"
  open -a Docker
  for _ in $(seq 1 60); do docker info >/dev/null 2>&1 && break; sleep 2; done
  docker info >/dev/null 2>&1 || { echo "Docker did not start. Open Docker Desktop and retry."; exit 1; }
fi

echo "Starting local Supabase…"
npx supabase start >/dev/null
eval "$(npx supabase status -o env | grep -E '^(API_URL|ANON_KEY|SERVICE_ROLE_KEY)=')"

echo "Applying schema + migrations…"
for f in docs/supabase-production-schema.sql $(ls docs/migrations/*.sql | sort); do
  docker exec -i supabase_db_medlane psql -U postgres -d postgres -v ON_ERROR_STOP=1 -q < "$f" >/dev/null 2>&1 || { echo "  failed: $f"; docker exec -i supabase_db_medlane psql -U postgres -d postgres -v ON_ERROR_STOP=1 -q < "$f"; exit 1; }
done
# PostgREST caches the schema; reload it so new tables/functions are visible.
docker exec -i supabase_db_medlane psql -U postgres -d postgres -q -c "notify pgrst, 'reload schema';" >/dev/null

cat > .dev.vars <<VARS
# Generated by tools/local/start.sh — local-only Supabase demo keys, not secrets. Never commit.
SUPABASE_URL=${API_URL}
SUPABASE_ANON_KEY=${ANON_KEY}
SUPABASE_SERVICE_ROLE_KEY=${SERVICE_ROLE_KEY}
ENVIRONMENT=local
APP_STATE_KEY=local
VARS

count=$(docker exec -i supabase_db_medlane psql -U postgres -d postgres -tAq -c "select count(*) from app_records where state_key = 'local';")
if [[ "${1:-}" == "--reseed" ]]; then
  node tools/local/seed.mjs --reset "${@:2}"
elif [[ "$count" == "0" ]]; then
  node tools/local/seed.mjs "${@:1}"
else
  echo "Local data present ($count records). Use --reseed to start over."
fi

echo
echo "Supabase Studio (browse the database): http://127.0.0.1:54323"
echo "App: http://127.0.0.1:8787  — sign in as superadmin@medlane.local / LocalTest!2026"
echo "Load test (another terminal): node tools/load-test.mjs --base-url http://127.0.0.1:8787 --accounts .local/accounts.csv --users 100"
echo
exec npx wrangler dev --local --ip 127.0.0.1 --port 8787
